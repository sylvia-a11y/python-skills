#syntaxName: List slice
#Format: List [start:stop]
#CRITICAL RULES!!!!
#1. "Start" is inclusive
#2. "Stop" is exclusive(stop before the stop index)
#3. If you omit "start", python will start from the beginning of the list(list[:stop])
#4. If you omit "stop", python will go until the end of the list(list[start:])
#5. Negative indices, python counts from the wright side